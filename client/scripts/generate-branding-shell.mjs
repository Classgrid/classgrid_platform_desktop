/**
 * generate-branding-shell.mjs
 *
 * Post-build script: reads dist/index.html and exports it as a JS string
 * so Vercel Edge Middleware can use it without fetching from itself.
 * 
 * Eliminates the internal fetch + infinite loop risk entirely.
 * Run after `vite build` — see package.json "build" script.
 */

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const distIndex = path.join(__dirname, "..", "dist", "index.html");
const output = path.join(__dirname, "..", "branding-shell.js");

try {
  const html = fs.readFileSync(distIndex, "utf8");
  const escaped = JSON.stringify(html);
  fs.writeFileSync(output, `// Auto-generated by scripts/generate-branding-shell.mjs — DO NOT EDIT\nexport const INDEX_HTML = ${escaped};\n`);
  console.log("✅ [Branding] Shell generated from dist/index.html");
} catch (err) {
  console.error("❌ [Branding] Failed to generate shell:", err.message);
  // Write a fallback so middleware still works
  fs.writeFileSync(output, `export const INDEX_HTML = null;\n`);
  process.exit(0); // Don't fail the build
}
